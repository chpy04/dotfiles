#!/usr/bin/env bash
set -euo pipefail

# ──────────────────────────────────────────────────────────────────────────────
# Dotfiles Installer (macOS)
# Symlinks config files to their expected locations.
# Usage:
#   ./install.sh             # link everything
#   ./install.sh --brew      # brew bundle install first, then link
#   ./install.sh --dry-run   # preview what would be linked
# ──────────────────────────────────────────────────────────────────────────────

DOTFILES_DIR="$(cd "$(dirname "$0")" && pwd)"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
BOLD='\033[1m'
NC='\033[0m'

DRY_RUN=false
RUN_BREW=false
LINKED=0
SKIPPED=0
BACKED_UP=0

# ──────────────────────────────────────────────────────────────────────────────
# Helpers
# ──────────────────────────────────────────────────────────────────────────────

info()    { echo -e "${BLUE}[info]${NC}  $*"; }
ok()      { echo -e "${GREEN}[ok]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[skip]${NC}  $*"; }
err()     { echo -e "${RED}[err]${NC}   $*"; }

link_file() {
    local src="$1"
    local dest="$2"

    if [ ! -e "$src" ] && [ ! -L "$src" ]; then
        err "Source does not exist: $src"
        return 1
    fi

    local dest_dir
    dest_dir="$(dirname "$dest")"

    if $DRY_RUN; then
        echo -e "  ${BOLD}would link${NC} $dest -> $src"
        return 0
    fi

    # Create parent directory if needed
    if [ ! -d "$dest_dir" ]; then
        mkdir -p "$dest_dir"
        info "Created directory: $dest_dir"
    fi

    # Handle existing files
    if [ -e "$dest" ] || [ -L "$dest" ]; then
        if [ -L "$dest" ]; then
            local current_target
            current_target="$(readlink "$dest")"
            if [ "$current_target" = "$src" ]; then
                warn "Already linked: $dest"
                SKIPPED=$((SKIPPED + 1))
                return 0
            fi
        fi
        # Back up existing file
        local backup="${dest}.backup.$(date +%Y%m%d%H%M%S)"
        mv "$dest" "$backup"
        info "Backed up: $dest -> $backup"
        BACKED_UP=$((BACKED_UP + 1))
    fi

    ln -sf "$src" "$dest"
    ok "Linked: $dest -> $src"
    LINKED=$((LINKED + 1))
}

# ──────────────────────────────────────────────────────────────────────────────
# Installers
# ──────────────────────────────────────────────────────────────────────────────

install_brew() {
    echo ""
    echo -e "${BOLD}── Homebrew bundle ──${NC}"
    echo ""

    if ! command -v brew &>/dev/null; then
        err "Homebrew not found. Install it from https://brew.sh first."
        exit 1
    fi

    if $DRY_RUN; then
        brew bundle check --file="$DOTFILES_DIR/brew/Brewfile" --verbose || true
    else
        brew bundle install --file="$DOTFILES_DIR/brew/Brewfile"
    fi
}

install_links() {
    echo ""
    echo -e "${BOLD}── Configs ──${NC}"
    echo ""

    local config_dir="$HOME/.config"

    # Zsh
    link_file "$DOTFILES_DIR/zsh/zshrc" "$HOME/.zshrc"
    link_file "$DOTFILES_DIR/zsh/zprofile" "$HOME/.zprofile"
    # Generated by `p10k configure`; copy it into zsh/p10k.zsh to track it
    if [ -f "$DOTFILES_DIR/zsh/p10k.zsh" ]; then
        link_file "$DOTFILES_DIR/zsh/p10k.zsh" "$HOME/.p10k.zsh"
    fi

    # Neovim
    link_file "$DOTFILES_DIR/nvim" "$config_dir/nvim"

    # Ghostty
    link_file "$DOTFILES_DIR/ghostty/config" "$config_dir/ghostty/config"

    # herdr (file only: the directory also holds sockets, logs and sessions)
    link_file "$DOTFILES_DIR/herdr/config.toml" "$config_dir/herdr/config.toml"

    # AeroSpace
    link_file "$DOTFILES_DIR/aerospace/aerospace.toml" "$HOME/.aerospace.toml"

    # Karabiner rewrites karabiner.json in place, which breaks a file symlink,
    # so link the whole directory (see karabiner-elements.pqrs.org/docs/manual/misc/configuration-file-path)
    link_file "$DOTFILES_DIR/karabiner" "$config_dir/karabiner"
    if ! $DRY_RUN && launchctl print "gui/$(id -u)/org.pqrs.service.agent.Karabiner-Console-User-Server" &>/dev/null; then
        launchctl kickstart -k "gui/$(id -u)/org.pqrs.service.agent.Karabiner-Console-User-Server"
        info "Restarted Karabiner to pick up the linked config"
    fi
}

# ──────────────────────────────────────────────────────────────────────────────
# Dependency checks
# ──────────────────────────────────────────────────────────────────────────────

check_dependencies() {
    local missing=()

    echo ""
    echo -e "${BOLD}── Checking dependencies ──${NC}"
    echo ""

    for cmd in brew git nvim aerospace herdr; do
        if command -v "$cmd" &>/dev/null; then
            ok "$cmd found: $(command -v "$cmd")"
        else
            warn "$cmd not found"
            missing+=("$cmd")
        fi
    done

    for app in Ghostty Karabiner-Elements; do
        if [ -d "/Applications/$app.app" ]; then
            ok "$app.app found"
        else
            warn "$app.app not found"
            missing+=("$app")
        fi
    done

    if [ ${#missing[@]} -gt 0 ]; then
        echo ""
        warn "Missing: ${missing[*]}"
        warn "Configs will still be linked. Run with --brew to install the Brewfile (herdr is installed separately)."
    fi
}

# ──────────────────────────────────────────────────────────────────────────────
# Summary
# ──────────────────────────────────────────────────────────────────────────────

print_summary() {
    echo ""
    echo -e "${BOLD}── Summary ──${NC}"
    echo ""
    if $DRY_RUN; then
        info "Dry run complete. No changes were made."
    else
        ok "Linked:    $LINKED"
        [ $SKIPPED -gt 0 ] && warn "Skipped:   $SKIPPED (already linked)"
        [ $BACKED_UP -gt 0 ] && info "Backed up: $BACKED_UP (old files saved with .backup.* suffix)"
    fi
    echo ""
}

# ──────────────────────────────────────────────────────────────────────────────
# Main
# ──────────────────────────────────────────────────────────────────────────────

main() {
    for arg in "$@"; do
        case "$arg" in
            --dry-run) DRY_RUN=true ;;
            --brew) RUN_BREW=true ;;
            -h|--help)
                echo "Usage: ./install.sh [--dry-run] [--brew]"
                echo ""
                echo "Options:"
                echo "  --dry-run   Preview what would be linked without making changes"
                echo "  --brew      Run brew bundle install on brew/Brewfile before linking"
                exit 0
                ;;
            *)
                err "Unknown argument: $arg"
                echo "Usage: ./install.sh [--dry-run] [--brew]"
                exit 1
                ;;
        esac
    done

    if [ "$(uname -s)" != "Darwin" ]; then
        err "These dotfiles are macOS-only."
        exit 1
    fi

    echo ""
    echo -e "${BOLD}Dotfiles Installer${NC}"
    echo -e "Source:   ${BOLD}$DOTFILES_DIR${NC}"
    $DRY_RUN && echo -e "${YELLOW}(dry run)${NC}"

    $RUN_BREW && install_brew

    check_dependencies

    install_links

    print_summary
}

main "$@"
